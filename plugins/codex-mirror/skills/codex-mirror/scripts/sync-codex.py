#!/usr/bin/env python3
"""Mirror a project's Claude Code agents and skills onto Codex.

Two things are mirrored, both with the Claude Code definitions as the source:

- agent definitions  ->  .codex/agents/<name>.toml
- .claude/skills/    ->  .agents/skills/           (verbatim copy)

The agents come from two places: the project's own `.claude/agents/*.md`, and the `agents/`
directory of every plugin the project enables in `.claude/settings.json`, read from the
installed copy of that plugin. Codex has no way to load a subagent from a plugin, so the
plugin that ships the agent cannot deliver it to Codex; this script does, from the consuming
project, which is the only place Codex looks.

What differs between the two runtimes is declared here, once, instead of being re-applied
by hand in every file:

- Codex does not auto-load `.claude/rules/*.md` by their `paths:` frontmatter, so agents
  are told to read them explicitly when the project has such rules.
- A Claude agent whose declared tools cannot write anything runs under a read-only sandbox.
- Model names differ. The table in `references/models.toml` maps each Claude model name to
  a Codex model; a project overrides an entry in `.codex/mirror.toml`.

Ownership of a generated file is written in its first line. A file that starts with the
generated header belongs to this script and is rewritten when its source changes. A file
whose first line carries `codex-mirror: manual` belongs to the project: the script never
touches it and only lists it. A file with neither marker was not produced here and is left
alone, reported so the project can choose.

Usage:
    python sync-codex.py            # write the generated files
    python sync-codex.py --check    # exit 1 if any generated file is missing or stale
    python sync-codex.py --hook     # SessionStart form: print only when something is wrong,
                                    # always exit 0

Runs from the project root, or from wherever CLAUDE_PROJECT_DIR points.
"""

from __future__ import annotations

import io
import json
import os
import pathlib
import re
import sys

try:
    import tomllib
except ModuleNotFoundError:  # Python < 3.11
    tomllib = None

HERE = pathlib.Path(__file__).resolve().parent
DEFAULT_MODELS = HERE.parent / "references" / "models.toml"

GENERATED = "# generated from {source} by codex-mirror; do not edit, run the codex-mirror skill"
MANUAL_MARK = "codex-mirror: manual"

# Tools that let an agent change something. An agent declaring tools and none of these runs
# read-only under Codex, where the sandbox enforces what the tool list only suggests.
WRITING_TOOLS = {"Write", "Edit", "MultiEdit", "NotebookEdit", "Bash", "PowerShell"}

PREAMBLE_HEAD = """## Running under Codex

This definition is generated by the codex-mirror plugin from
`{source}`.
Edit that file, then regenerate. Never edit this TOML by hand; to take it over, replace its
first line with `# codex-mirror: manual`.
"""

PREAMBLE_RULES = """
- **The rule files are not auto-loaded here.** Glob `.claude/rules/**/*.md`, read the `paths:`
  frontmatter of each, and read in full every rule whose glob matches a file you are about to
  read or write, plus every rule without a `paths:` field. Under Claude Code they arrive on
  their own; here they do not.
"""

PREAMBLE_SKILLS = """
- **Skills are invoked by name.** The project's own skills are mirrored to `.agents/skills/`,
  and plugin skills are installed in Codex through their plugin; both are discovered natively.
  A name written `<plugin>:<skill>` below means the skill `<skill>`.
"""

PREAMBLE_PLUGIN_ROOT = """
- **`${{CLAUDE_PLUGIN_ROOT}}` is the installed root of the `{plugin}` plugin**:
  `~/.codex/plugins/cache/{marketplace}/{plugin}/<version>/` when installed through Codex,
  `~/.claude/plugins/cache/{marketplace}/{plugin}/<version>/` otherwise. Resolve it before
  running a command that names it.
"""

PREAMBLE_READ_ONLY = """
- **You write nothing at all.** The sandbox is read-only. Where the instructions below say to
  write a report to a path, return the exact report content and that target path instead; the
  parent persists it verbatim.
"""


class Report:
    def __init__(self) -> None:
        self.red: list[str] = []
        self.warn: list[str] = []
        self.info: list[str] = []
        self.written = 0

    def print(self, hook: bool) -> None:
        for line in self.red:
            print(f"RED   {line}")
        for line in self.warn:
            print(f"WARN  {line}")
        if not hook:
            for line in self.info:
                print(f"INFO  {line}")


# --------------------------------------------------------------------------- inputs


def project_root() -> pathlib.Path:
    env = os.environ.get("CLAUDE_PROJECT_DIR")
    return pathlib.Path(env).resolve() if env else pathlib.Path.cwd().resolve()


def load_toml(path: pathlib.Path) -> dict:
    if not path.is_file():
        return {}
    if tomllib is None:
        raise SystemExit("Python 3.11 or newer is required to read TOML")
    with io.open(path, "rb") as handle:
        return tomllib.load(handle)


def load_settings(root: pathlib.Path) -> dict[str, bool]:
    """Enabled plugins, `name@marketplace` -> bool, from the project's settings files."""
    enabled: dict[str, bool] = {}
    for name in ("settings.json", "settings.local.json"):
        path = root / ".claude" / name
        if not path.is_file():
            continue
        try:
            data = json.loads(io.open(path, encoding="utf-8").read())
        except json.JSONDecodeError as error:
            raise SystemExit(f"{path}: {error}")
        for key, value in (data.get("enabledPlugins") or {}).items():
            enabled[key] = bool(value)
    return enabled


def same_path(a: str, b: pathlib.Path) -> bool:
    try:
        return pathlib.Path(a).resolve() == b
    except OSError:
        return False


def installed_plugin_root(key: str, root: pathlib.Path) -> pathlib.Path | None:
    """Where the installed copy of an enabled plugin lives on this machine.

    Claude Code's install record first, the project-scoped entry before the user-scoped one;
    then the Codex plugin cache; then the Claude plugin cache, newest version last.
    """
    home = pathlib.Path.home()
    plugin, _, marketplace = key.partition("@")

    record = home / ".claude" / "plugins" / "installed_plugins.json"
    if record.is_file():
        try:
            entries = json.loads(io.open(record, encoding="utf-8").read()).get("plugins", {}).get(key, [])
        except json.JSONDecodeError:
            entries = []
        ranked = sorted(
            entries,
            key=lambda e: (
                0 if e.get("scope") == "project" and same_path(e.get("projectPath", ""), root) else
                1 if e.get("scope") == "user" else 2
            ),
        )
        for entry in ranked:
            path = pathlib.Path(entry.get("installPath", ""))
            if path.is_dir():
                return path

    for cache in (
        home / ".codex" / "plugins" / "cache" / marketplace / plugin,
        home / ".claude" / "plugins" / "cache" / marketplace / plugin,
    ):
        if cache.is_dir():
            versions = sorted((p for p in cache.iterdir() if p.is_dir()), key=version_key)
            if versions:
                return versions[-1]
    return None


def version_key(path: pathlib.Path) -> tuple:
    parts = re.split(r"[.\-]", path.name)
    return tuple((0, int(p)) if p.isdigit() else (1, p) for p in parts)


def plugin_version(plugin_root: pathlib.Path) -> str:
    for manifest in (plugin_root / ".claude-plugin" / "plugin.json", plugin_root / "plugin.json"):
        if manifest.is_file():
            try:
                return str(json.loads(io.open(manifest, encoding="utf-8").read()).get("version", "?"))
            except json.JSONDecodeError:
                return "?"
    return plugin_root.name


# --------------------------------------------------------------------------- agents


def parse_agent(path: pathlib.Path) -> tuple[dict, str]:
    """Split a Claude agent definition into its frontmatter and its body."""
    text = io.open(path, encoding="utf-8").read()
    match = re.match(r"^---\r?\n(.*?)\r?\n---\r?\n(.*)$", text, re.S)
    if not match:
        raise SystemExit(f"{path}: no frontmatter")

    front: dict = {}
    current_list: str | None = None
    for line in match.group(1).splitlines():
        item = re.match(r"^\s+-\s+(.*)$", line)
        if item and current_list:
            front.setdefault(current_list, []).append(item.group(1).strip())
            continue
        pair = re.match(r"^([A-Za-z_-]+):\s*(.*)$", line)
        if pair:
            key, value = pair.group(1), pair.group(2).strip()
            if value == "":
                current_list = key
                front.setdefault(key, [])
            else:
                current_list = None
                front[key] = value
    for key in ("name", "description"):
        if key not in front:
            raise SystemExit(f"{path}: missing '{key}' in the frontmatter")
    if front["name"] != path.stem:
        raise SystemExit(f"{path}: name '{front['name']}' does not match the file name")
    return front, match.group(2).strip()


def declared_tools(front: dict) -> set[str] | None:
    tools = front.get("tools")
    if tools is None:
        return None
    if isinstance(tools, list):
        return {t.strip() for t in tools}
    return {t.strip() for t in re.split(r",\s*", tools) if t.strip()}


def toml_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(
    front: dict,
    body: str,
    source: str,
    plugin: tuple[str, str] | None,
    models: dict,
    has_rules: bool,
    report: Report,
) -> str:
    """Build the TOML Codex reads from the Markdown Claude Code reads."""
    name = front["name"]
    overrides = (models.get("agents") or {}).get(name, {})

    tools = declared_tools(front)
    read_only = overrides.get("sandbox_mode", None)
    if read_only is None:
        read_only = "read-only" if tools is not None and not (tools & WRITING_TOOLS) else None
    elif read_only != "read-only":
        read_only = None

    preamble = PREAMBLE_HEAD.format(source=source)
    preamble += "\nWhat differs from the Claude Code runtime, and changes what you must do:\n"
    if has_rules:
        preamble += PREAMBLE_RULES
    preamble += PREAMBLE_SKILLS
    if plugin and "${CLAUDE_PLUGIN_ROOT}" in body:
        preamble += PREAMBLE_PLUGIN_ROOT.format(plugin=plugin[0], marketplace=plugin[1])
    if read_only:
        preamble += PREAMBLE_READ_ONLY

    instructions = f"{preamble}\n---\n\n{body}"
    if "'''" in instructions:
        raise SystemExit(f"{source}: body contains ''' and cannot be embedded in TOML")

    lines = [
        GENERATED.format(source=source),
        f"name = {toml_string(name)}",
        f"description = {toml_string(front['description'])}",
    ]

    model_name = overrides.get("model") or resolve_model(front.get("model"), models, source, report)
    if model_name:
        lines.append(f"model = {toml_string(model_name)}")

    effort = overrides.get("effort") or front.get("effort")
    if effort:
        mapped = (models.get("efforts") or {}).get(effort)
        if mapped:
            lines.append(f"model_reasoning_effort = {toml_string(mapped)}")
        else:
            report.warn.append(f"{source}: effort '{effort}' has no Codex equivalent in the model table")

    if read_only:
        lines.append('sandbox_mode = "read-only"')
    lines.append("developer_instructions = '''")
    lines.append(instructions)
    lines.append("'''")
    return "\n".join(lines) + "\n"


def resolve_model(claude_model: str | None, models: dict, source: str, report: Report) -> str | None:
    if not claude_model:
        return None
    table = models.get("models") or {}
    if claude_model in table:
        return table[claude_model]
    report.warn.append(
        f"{source}: model '{claude_model}' has no Codex equivalent in the model table, "
        "the agent inherits the session model"
    )
    return None


def collect_agents(root: pathlib.Path, report: Report) -> list[tuple[pathlib.Path, str, tuple[str, str] | None]]:
    """(path, source label, (plugin, marketplace) or None) for every agent to mirror.

    A project agent shadows a plugin agent of the same name, as it does under Claude Code.
    """
    agents: dict[str, tuple[pathlib.Path, str, tuple[str, str] | None]] = {}

    local = root / ".claude" / "agents"
    if local.is_dir():
        for path in sorted(local.glob("*.md")):
            agents[path.stem] = (path, path.relative_to(root).as_posix(), None)

    for key, enabled in sorted(load_settings(root).items()):
        if not enabled:
            continue
        plugin, _, marketplace = key.partition("@")
        install = installed_plugin_root(key, root)
        if install is None:
            report.warn.append(f"plugin {key} is enabled but not installed on this machine, its agents are not mirrored")
            continue
        agents_dir = install / "agents"
        if not agents_dir.is_dir():
            continue
        version = plugin_version(install)
        for path in sorted(agents_dir.glob("*.md")):
            if path.stem in agents:
                shadow = agents[path.stem]
                if shadow[2] is None:
                    report.info.append(f"{shadow[1]} shadows {key}:agents/{path.name}")
                    continue
                raise SystemExit(f"agent '{path.stem}' is shipped by both {shadow[2][0]} and {plugin}")
            agents[path.stem] = (path, f"{key} {version} agents/{path.name}", (plugin, marketplace))

    return [agents[name] for name in sorted(agents)]


def first_line(path: pathlib.Path) -> str:
    with io.open(path, encoding="utf-8") as handle:
        return handle.readline().rstrip("\r\n")


def sync_agents(root: pathlib.Path, models: dict, check: bool, report: Report) -> None:
    target_dir = root / ".codex" / "agents"
    has_rules = (root / ".claude" / "rules").is_dir()
    sources = collect_agents(root, report)
    expected: set[str] = set()

    if sources:
        target_dir.mkdir(parents=True, exist_ok=True)

    for path, source, plugin in sources:
        front, body = parse_agent(path)
        target = target_dir / f"{front['name']}.toml"
        expected.add(target.name)

        if target.exists():
            head = first_line(target)
            if MANUAL_MARK in head:
                report.info.append(f"{target.relative_to(root).as_posix()} is maintained by hand, source {source} not applied")
                continue
            if not head.startswith("# generated from "):
                report.warn.append(
                    f"{target.relative_to(root).as_posix()} was not generated here and is left alone; "
                    f"add '# {MANUAL_MARK}' as its first line to keep it, or delete it to let {source} take over"
                )
                continue

        rendered = render(front, body, source, plugin, models, has_rules, report)
        current = io.open(target, encoding="utf-8").read() if target.exists() else None
        if current == rendered:
            continue
        rel = target.relative_to(root).as_posix()
        if check:
            report.red.append(f"{rel} is {'missing' if current is None else 'stale'} against {source}")
            continue
        io.open(target, "w", encoding="utf-8", newline="\n").write(rendered)
        report.written += 1
        print(f"wrote {rel}")

    if not target_dir.is_dir():
        return
    for orphan in sorted(target_dir.glob("*.toml")):
        if orphan.name in expected:
            continue
        head = first_line(orphan)
        rel = orphan.relative_to(root).as_posix()
        if MANUAL_MARK in head:
            report.info.append(f"{rel} is maintained by hand and has no Claude Code source")
            continue
        if not head.startswith("# generated from "):
            report.warn.append(
                f"{rel} was not generated here and has no Claude Code source; left alone, "
                f"add '# {MANUAL_MARK}' as its first line to silence this"
            )
            continue
        if check:
            report.red.append(f"{rel} has no source any more")
        else:
            orphan.unlink()
            print(f"removed {rel}")


# --------------------------------------------------------------------------- skills


def sync_skills(root: pathlib.Path, check: bool, report: Report) -> None:
    """Copy .claude/skills/ to .agents/skills/ verbatim. No transformation applies."""
    source_dir = root / ".claude" / "skills"
    target_dir = root / ".agents" / "skills"
    if not source_dir.is_dir():
        return

    expected: set[pathlib.Path] = set()
    for source in sorted(p for p in source_dir.rglob("*") if p.is_file()):
        target = target_dir / source.relative_to(source_dir)
        expected.add(target)
        wanted = source.read_bytes()
        current = target.read_bytes() if target.exists() else None
        if current == wanted:
            continue
        rel = target.relative_to(root).as_posix()
        if check:
            report.red.append(f"{rel} is {'missing' if current is None else 'stale'}")
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(wanted)
        report.written += 1
        print(f"wrote {rel}")

    if not target_dir.is_dir():
        return
    for orphan in sorted(p for p in target_dir.rglob("*") if p.is_file()):
        if orphan in expected:
            continue
        rel = orphan.relative_to(root).as_posix()
        if check:
            report.red.append(f"{rel} has no source under .claude/skills/")
        else:
            orphan.unlink()
            print(f"removed {rel}")
    for folder in sorted((p for p in target_dir.rglob("*") if p.is_dir()), reverse=True):
        if not check and not any(folder.iterdir()):
            folder.rmdir()


# --------------------------------------------------------------------------- models


def load_models(root: pathlib.Path) -> dict:
    """The plugin's table, with the project's `.codex/mirror.toml` merged over it."""
    models = load_toml(DEFAULT_MODELS)
    override = load_toml(root / ".codex" / "mirror.toml")
    for section in ("models", "efforts"):
        merged = dict(models.get(section) or {})
        merged.update(override.get(section) or {})
        models[section] = merged
    agents = dict(models.get("agents") or {})
    for name, values in (override.get("agents") or {}).items():
        agents[name] = {**agents.get(name, {}), **values}
    models["agents"] = agents
    return models


def check_model_lifetimes(models: dict, report: Report) -> None:
    """Compare the table with the model list Codex itself caches. Best effort, never fatal."""
    cache = pathlib.Path.home() / ".codex" / "models_cache.json"
    if not cache.is_file():
        return
    try:
        listed = json.loads(io.open(cache, encoding="utf-8").read()).get("models", [])
    except (json.JSONDecodeError, OSError):
        return
    by_slug = {m.get("slug"): m for m in listed if isinstance(m, dict)}
    if not by_slug:
        return
    used = set((models.get("models") or {}).values())
    used.update(v.get("model") for v in (models.get("agents") or {}).values() if v.get("model"))
    for slug in sorted(used):
        entry = by_slug.get(slug)
        if entry is None:
            report.warn.append(f"model '{slug}' is not in the list Codex fetched last, check the model table")
            continue
        upgrade = entry.get("upgrade") or {}
        if upgrade.get("model"):
            when = upgrade.get("retirement_at", "an unannounced date")
            report.warn.append(f"model '{slug}' retires on {when}, Codex points to '{upgrade['model']}'")


# --------------------------------------------------------------------------- main


def main(argv: list[str]) -> int:
    check = "--check" in argv or "--hook" in argv
    hook = "--hook" in argv
    root = project_root()
    report = Report()

    if not (root / ".claude").is_dir():
        if hook:
            return 0
        print(f"RED   {root} has no .claude/ directory")
        return 1

    models = load_models(root)
    sync_agents(root, models, check, report)
    sync_skills(root, check, report)
    check_model_lifetimes(models, report)

    report.print(hook)
    if hook:
        if report.red:
            print(
                f"\ncodex-mirror: {len(report.red)} generated file(s) out of date. "
                "Run the codex-mirror skill to regenerate them before working under Codex."
            )
        return 0
    if check:
        if report.red:
            print(f"\n{len(report.red)} problem(s). Run the codex-mirror skill to regenerate.")
            return 1
        print("GREEN  every Codex agent and shared skill matches its Claude Code source")
        return 0
    print(f"{report.written} file(s) written")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
